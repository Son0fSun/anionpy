/// `logfactorial(k)`: `log(k!)`.
pub fn logfactorial(k: i64) -> f64 {
    const HALF_LN_2PI: f64 = 0.918_938_533_204_672_8;
    if (k as usize) < LOGFACT.len() {
        return LOGFACT[k as usize];
    }
    let kf = k as f64;
    (kf + 0.5) * kf.ln() - kf + (HALF_LN_2PI + (1.0 / kf) * (1.0 / 12.0 - 1.0 / (360.0 * kf * kf)))
}
