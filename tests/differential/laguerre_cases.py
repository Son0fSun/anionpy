def _canonical_root_order(arr):
    """See legendre_cases.py's `_canonical_root_order` -- identical
    stabilization strategy (round the sort KEY, not the compared values,
    to 6 decimals -- three orders of magnitude coarser than
    LAGROOTS_COMPLEX_EPS below), used here for the SAME reason: two
    independent eigensolvers landing on differently-signed near-zero roots
    must not spuriously fail on ordering alone. `lagroots`'s output dtype
    also depends on `_to_real_if_imag_zero`-equivalent downcasting (see
    anionpy/polynomial/laguerre.py's `lagroots`), so `arr` may be real or
    complex depending on the case; `.real`/`.imag` both work on a real
    float64 array (imag is all zero) so this helper is dtype-agnostic."""
    arr = np.asarray(arr)
    key = list(zip(np.round(arr.real, 6), np.round(np.imag(arr), 6)))
    order = sorted(range(len(arr)), key=lambda i: key[i])
    return arr[order]


def _lagroots_numpy_sorted(c):
    return _canonical_root_order(np.polynomial.laguerre.lagroots(c))


def _lagroots_ionp_sorted(c):
    import anionpy as ap
    r = ap.polynomial.laguerre.lagroots(ap.array(c))
    r_np = np.asarray(r.tolist() if hasattr(r, "tolist") else r)
    return _canonical_root_order(r_np)


