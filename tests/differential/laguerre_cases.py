def lagval_cases():
    cases = []
    for c_label, c in [("int_c", INT_C), ("float_c", FLOAT_C), ("bool_c", BOOL_C),
                        ("complex_c", COMPLEX_C), ("trailing_zero_c", TRAILING_ZERO_C),
                        ("single_c", SINGLE_C)]:
        cases.append((f"scalar_x__{c_label}", (X_SCALAR, c), {}))
        cases.append((f"list_x__{c_label}", (XS, c), {}))
        cases.append((f"complex_x__{c_label}", (X_COMPLEX, c), {}))
    cases.append(("array_x_2d", (np.array([[0.0, 1.0], [2.0, 3.0]]), FLOAT_C), {}))
    # degree-2 coefficient array (len(c) == 3 hits the general Clenshaw
    # loop; len(c) == 2 hits the dedicated short-circuit branch
    # `c0=c[0]; c1=c[1]` inside lagval itself) -- pinned explicitly.
    cases.append(("len2_c_pinned", (XS, C1_SHORT), {}))
    cases.append(("len1_c_pinned", (XS, SINGLE_C), {}))
    # ---- Added 2026-08-07 (Monday): real-coefficient/complex-x regression
    # guard, multiple degrees. `lag_eval`'s Clenshaw recursion needed a
    # dedicated hybrid-typed kernel (`lag_eval_real_coef_complex_x` in
    # `ionp-core/src/laguerre.rs`) to match NumPy's "accumulator stays
    # real-typed until touched by the complex x" scalar semantics -- the
    # bug was invisible to the corpus above because none of its real-
    # coefficient cases have length >= 4 AND an evaluation point whose
    # divisor (3, 5, 6, ...) is not a power of 2 (`complex_div`'s Smith's-
    # algorithm real/real path only disagrees with plain division on
    # non-power-of-2 divisors -- measured directly, ~33% mismatch on 3/5/6
    # vs. 0% on 2/4). These four pin exactly that combination, real
    # coefficients of length 4-7 (so the loop passes through divisors
    # 3, 4, 5, 6) at a non-"nice" complex x.
    _real_x_complex = 0.9505 - 1.3820j
    cases.append(("real_c_len4_complex_x_DEGREE_REGRESSION",
                   (_real_x_complex, [0.5993, -1.21, 2.07, 0.44]), {}))
    cases.append(("real_c_len5_complex_x_DEGREE_REGRESSION",
                   (_real_x_complex, [0.5993, -1.21, 2.07, 0.44, -0.83]), {}))
    cases.append(("real_c_len6_complex_x_DEGREE_REGRESSION",
                   (_real_x_complex, [0.5993, -1.21, 2.07, 0.44, -0.83, 1.6]), {}))
    cases.append(("real_c_len7_complex_x_DEGREE_REGRESSION",
                   (_real_x_complex, [0.5993, -1.21, 2.07, 0.44, -0.83, 1.6, -2.05]), {}))
    return cases


