"""anionpy.polynomial.laguerre.* differential registry entries.

NEW FILE (same pattern as legendre_cases.py/polynomial_cases.py/
linalg_cases.py): builds a `LAGUERRE_SPECS: dict[str, ItemSpec]` dict,
merged into `registry.REGISTRY` at the bottom of registry.py
(collision-checked, same pattern as every other `*_cases.py` merge).

Covers the same ~24 non-N-D items as legendre_cases.py's scope
(`Laguerre(ABCPolyBase)` and `*2d`/`*3d`/`*nd` composition items are NOT
covered, not attempted in this pass).

Laguerre looks like Legendre and is NOT -- this corpus is deliberately NOT
a relabeled copy of legendre_cases.py's case VALUES (though its structural
shape is intentionally identical, to keep the two bases easy to diff).
Specific divergences a naive copy-paste would miss, each pinned explicitly
below:
  - `lagline(off, scl)` returns `[off+scl, -scl]`, not `[off, scl]` --
    `legline_cases`' exact argument tuples would silently pass even with a
    swapped-in `legline` implementation if the EXPECTED values weren't
    independently generated by calling real numpy; since every case here
    is graded by calling `np.polynomial.laguerre.lagline` directly (no
    hardcoded expected arrays), this is caught structurally rather than by
    a hand-written assertion.
  - `lagcompanion`/`lagroots` have a `len(c) == 2` special case that
    returns `1 + c0/c1` (NOT Legendre's `-c0/c1`) -- this is the
    "degree-2 coefficient array" special case analogous to the
    herm2poly `n==2` bug the task brief warned about, and it is pinned
    EXPLICITLY below (not left to random sampling) as `degree1_pinned`
    (a length-2 coefficient array is polynomial degree 1, but it is the
    `len(c) == 2` BRANCH that is special-cased in the source, hence
    "degree1_pinned" names the polynomial degree while the comment calls
    out the branch condition precisely).
  - `laggauss` does NOT symmetrize (`x`/`w` are used exactly as the
    eigensolver + Newton polish produce them) and normalizes with
    `w /= w.sum()` -- NO leading factor of 2 (contrast Legendre's
    `w = w * (2.0 / w.sum())`).
  - `lagweight(x) = exp(-x)`, domain `[0, inf)` -- unlike `legweight`'s
    `x*0 + 1`, this is a real function of `x` and needs points that probe
    both the `[0, inf)` domain interior and negative/domain-violating `x`
    (numpy raises no domain error -- `exp(-x)` is defined everywhere;
    verified live: `NL.lagweight(-1.0)` returns `2.718281828459045`, no
    exception).
"""
